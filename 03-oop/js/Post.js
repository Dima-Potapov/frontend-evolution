/**
 * ============================================================
 *  Post.js — МОДЕЛЬ одного поста
 * ============================================================
 *
 * [v1, v2]: пост был простым объектом-литералом:
 *     { id: 1, title: '...', body: '...', likes: 0 }
 * Любой код мог написать post.likes = -100 или post.id = 'abc',
 * и никто бы этому не помешал.
 *
 * [v3, ООП]: пост — ОБЪЕКТ КЛАССА Post. Класс — это «чертёж»,
 * по которому создаются объекты с одинаковой структурой и поведением.
 * Данные (поля) и действия над ними (методы) живут ВМЕСТЕ.
 * Это и есть ИНКАПСУЛЯЦИЯ — первый кит ООП:
 *   «спрятать внутреннее устройство и дать наружу только безопасные методы».
 *
 * Например, лайки теперь нельзя уменьшить или сломать снаружи:
 * их можно только увеличить методом like().
 */

export class Post {
  /**
   * static #nextId — СТАТИЧЕСКОЕ приватное поле.
   *
   * static = принадлежит самому КЛАССУ, а не отдельным объектам.
   * Обычное поле: у каждого поста своё (у поста №1 свой title, у №2 свой).
   * Статическое поле: ОДНО на весь класс, общее для всех постов.
   *
   * Идеально для счётчика ID: каждый новый пост берёт текущее значение
   * и увеличивает его, и ID никогда не повторяются.
   *
   * [v1, v2]: счётчик был глобальной переменной let nextId = 1,
   * которую мог случайно изменить любой код. Здесь он спрятан внутри класса.
   */
  static #nextId = 1;

  /**
   * Приватные поля экземпляра. У КАЖДОГО поста — свои значения.
   * Снаружи до них не добраться: post.#likes → SyntaxError.
   */
  #id;
  #title;
  #body;
  #likes = 0; // значение по умолчанию: новый пост без лайков

  /**
   * constructor — специальный метод, который вызывается при `new Post(...)`.
   *
   * Что делает `new` под капотом:
   *   1. создаёт пустой объект {};
   *   2. связывает его с прототипом Post.prototype (оттуда берутся методы);
   *   3. инициализирует поля (#id, #likes = 0 ...);
   *   4. вызывает constructor, где this = этот новый объект;
   *   5. возвращает объект.
   *
   * @param {string} title — заголовок
   * @param {string} body — текст
   */
  constructor(title, body) {
    // Простая валидация: модель сама защищает себя от некорректных данных.
    // В v1/v2 проверка была только в обработчике формы.
    if (!title.trim() || !body.trim()) {
      // throw — «выбросить» ошибку. Выполнение метода прерывается,
      // а ошибку можно поймать снаружи через try/catch.
      throw new Error('У поста должны быть заголовок и текст');
    }

    // Post.#nextId++ — берём текущее значение, ПОТОМ увеличиваем на 1.
    // Обращаемся через имя класса, потому что поле статическое.
    this.#id = Post.#nextId++;
    this.#title = title.trim();
    this.#body = body.trim();
  }

  /**
   * ГЕТТЕРЫ (get) — «свойства только для чтения».
   *
   * Снаружи пишем post.title (без скобок!), как будто это обычное поле,
   * а на самом деле вызывается этот метод.
   * Сеттера (set) нет, поэтому post.title = 'новое' ничего не изменит
   * (а в строгом режиме модулей — выбросит TypeError).
   *
   * Так мы даём читать данные, но не даём их ломать.
   */
  get id() {
    return this.#id;
  }

  get title() {
    return this.#title;
  }

  get body() {
    return this.#body;
  }

  get likes() {
    return this.#likes;
  }

  /**
   * like — ЕДИНСТВЕННЫЙ способ изменить лайки.
   * Метод описывает ДЕЙСТВИЕ предметной области («лайкнуть»),
   * а не техническое «присвоить число».
   *
   * Методы класса хранятся НЕ в каждом объекте, а один раз
   * в Post.prototype. Все посты пользуются одной и той же функцией,
   * а this внутри указывает на тот пост, у которого метод вызвали.
   */
  like() {
    this.#likes += 1;
  }
}

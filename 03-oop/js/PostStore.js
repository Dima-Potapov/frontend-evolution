/**
 * ============================================================
 *  PostStore.js — ХРАНИЛИЩЕ всех постов (слой данных)
 * ============================================================
 *
 * [v1, v2]: массив posts был глобальной переменной (let posts = []),
 * и менять его мог любой кусок кода как угодно.
 *
 * [v3]: массив спрятан внутри класса. Менять данные можно только
 * через методы add / like / remove. После каждого изменения хранилище
 * само сообщает подписчикам: «данные поменялись!» (событие 'change').
 *
 * Этот класс НИЧЕГО не знает про HTML, DOM, кнопки и формы.
 * Его можно перенести в Node.js, в мобильное приложение или
 * покрыть тестами без браузера. Это принцип РАЗДЕЛЕНИЯ ОТВЕТСТВЕННОСТИ.
 *
 * 💡 В версии 06 эту роль сыграет библиотека Zustand:
 * там тоже будет «стор» с данными и действиями (addPost, likePost...).
 */

// import — берём классы из других модулей.
// Путь './Post.js' — относительно ТЕКУЩЕГО файла; расширение .js
// в браузере обязательно (сборщики вроде Vite позволяют его опускать).
import { EventEmitter } from './EventEmitter.js';
import { Post } from './Post.js';

/**
 * extends — НАСЛЕДОВАНИЕ (второй кит ООП).
 *
 * PostStore «наследует» всё, что умеет EventEmitter: методы on() и emit().
 * Писать их заново не нужно. PostStore «является» EventEmitter'ом
 * (отношение «is-a»): store.on('change', ...) работает сразу.
 *
 * Под капотом: PostStore.prototype ссылается на EventEmitter.prototype.
 * Если метода нет у PostStore, JS ищет его выше по ЦЕПОЧКЕ ПРОТОТИПОВ.
 */
export class PostStore extends EventEmitter {
  /**
   * Приватный массив постов. Снаружи его не видно и не изменить.
   * Важно: приватное поле #listeners родителя здесь ТОЖЕ недоступно.
   * Приватность в JS — «только этот класс», даже наследники не видят.
   */
  #posts = [];

  /**
   * Здесь нет constructor, и это нормально. Если его не написать,
   * JS неявно создаст такой:
   *     constructor(...args) { super(...args); }
   * super(...) — вызов конструктора РОДИТЕЛЯ (EventEmitter).
   * Если бы мы писали свой constructor, super() пришлось бы вызвать
   * ПЕРВЫМ, до любого обращения к this, иначе будет ошибка.
   */

  /**
   * getAll — вернуть посты для отображения.
   *
   * Возвращаем КОПИЮ массива ([...this.#posts]), а не сам массив.
   * Если отдать оригинал, внешний код мог бы сделать posts.push(...)
   * или posts.length = 0 в обход хранилища, и подписчики бы не узнали.
   * Сами объекты Post менять снаружи и так нельзя (приватные поля).
   *
   * Новые посты должны быть сверху, поэтому мы храним их
   * в порядке «новые в начале» (см. unshift в методе add).
   */
  getAll() {
    return [...this.#posts];
  }

  /**
   * add — создать и добавить пост.
   * new Post(...) может выбросить ошибку (пустой заголовок),
   * тогда до unshift и emit дело не дойдёт: данные останутся корректными.
   */
  add(title, body) {
    const post = new Post(title, body);

    // unshift — добавить В НАЧАЛО массива (новые посты сверху).
    this.#posts.unshift(post);

    // Сообщаем подписчикам. Это и есть «автоматическая» перерисовка:
    // хранилище не вызывает render само, оно просто кричит «изменилось!».
    this.#notify();
  }

  /**
   * like — лайкнуть пост по id.
   * Сам лайк выполняет МОДЕЛЬ (post.like()), хранилище только находит пост.
   * Каждый класс отвечает за своё.
   */
  like(id) {
    // find — вернёт первый пост с подходящим id или undefined.
    const post = this.#posts.find((p) => p.id === id);

    // ?. — опциональная цепочка: если post === undefined,
    // метод like просто не вызовется (вместо ошибки).
    post?.like();

    this.#notify();
  }

  /**
   * remove — удалить пост по id.
   * filter создаёт НОВЫЙ массив без удаляемого поста.
   * (Иммутабельный подход: не «вырезаем» из старого массива, а создаём новый.
   *  В React (05) так придётся делать ОБЯЗАТЕЛЬНО, привыкаем заранее.)
   */
  remove(id) {
    this.#posts = this.#posts.filter((p) => p.id !== id);
    this.#notify();
  }

  /**
   * #notify — ПРИВАТНЫЙ МЕТОД (тоже с #).
   * Вызвать его можно только изнутри класса: store.#notify() снаружи — ошибка.
   * Это внутренняя «кухня» хранилища, наружу она не нужна.
   *
   * this.emit — метод, УНАСЛЕДОВАННЫЙ от EventEmitter.
   */
  #notify() {
    this.emit('change', this.getAll());
  }
}

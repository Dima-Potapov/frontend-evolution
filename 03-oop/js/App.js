/*
 * ============================================================
 *  App.js — КОНТРОЛЛЕР (Controller), «дирижёр» приложения
 * ============================================================
 *
 *  Что уже есть к этому моменту:
 *   • PostStore    — МОДЕЛЬ: хранит данные и сообщает «я изменился» (событие 'change').
 *   • PostView     — ПРЕДСТАВЛЕНИЕ: умеет рисовать список и сообщать о кликах.
 *   • PostFormView — ПРЕДСТАВЛЕНИЕ формы: сообщает «форму отправили».
 *
 *  Важно: ни один из этих классов НЕ ЗНАЕТ о других.
 *   - Store не знает, что его рисуют в DOM (его можно было бы рисовать в консоли).
 *   - View не знает, откуда берутся посты и что значит «лайк».
 *
 *  Кто-то должен их СВЯЗАТЬ. Этим и занимается App:
 *   «Когда View говорит "кликнули лайк" → попроси Store поставить лайк.
 *    Когда Store говорит "я изменился" → попроси View перерисоваться.»
 *
 *  Сравнение с прошлыми версиями:
 *   • v1 (vanilla) и v2 (jQuery): в одном файле была ПЕРЕМЕШАНА вся логика —
 *     массив posts, функция render, обработчики кликов. Один обработчик сам
 *     менял массив, сам вызывал render, сам лез в DOM.
 *   • v3 (ООП): каждая обязанность живёт в своём классе, а App — лишь «провода»
 *     между ними. Он очень короткий, и это хороший знак.
 *
 *  Связь с будущим:
 *   В React/Vue роль App частично берёт на себя сам фреймворк: вы пишете
 *   «состояние» и «как его показать», а связывание (подписки, перерисовки)
 *   фреймворк делает автоматически. Здесь мы делаем это РУКАМИ, чтобы понять,
 *   что именно фреймворк делает за нас.
 */

export class App {
  // Приватные поля: снаружи нельзя написать app.#store = ... — будет SyntaxError.
  // Это инкапсуляция: App сам решает, кому и как давать доступ к своим частям.
  #store;
  #postView;
  #formView;

  /*
   * Конструктор принимает ОБЪЕКТ с зависимостями, а не создаёт их сам.
   * Это называется «внедрение зависимостей» (Dependency Injection).
   *
   * Зачем? App не должен знать, КАК создаются Store и View
   * (какие DOM-элементы им передать и т.п.). Он получает готовые детали.
   * Плюсы:
   *   - в тестах можно передать «фальшивый» store или view (mock);
   *   - можно заменить PostView на, скажем, TablePostView, не трогая App.
   *
   * Деструктуризация { store, postView, formView } в параметрах —
   * это просто удобный синтаксис: вытаскиваем свойства объекта в переменные.
   */
  constructor({ store, postView, formView }) {
    this.#store = store;
    this.#postView = postView;
    this.#formView = formView;

    // Сразу «прокладываем провода» между частями.
    this.#bindEvents();
  }

  /*
   * #bindEvents — приватный метод, где настраиваются все подписки.
   * Вынесено в отдельный метод, чтобы конструктор оставался коротким и читаемым.
   */
  #bindEvents() {
    /* ---------- 1. Модель → Представление ----------
     * Подписываемся на событие 'change' у Store.
     * Каждый раз, когда данные меняются (add/like/remove), Store вызывает emit('change', posts),
     * а мы в ответ перерисовываем список.
     *
     * Это и есть ОДНОНАПРАВЛЕННЫЙ поток данных:
     *   действие → изменение модели → событие → перерисовка.
     * В v1/v2 мы вызывали render() вручную после КАЖДОГО изменения — легко забыть.
     * Теперь перерисовка гарантирована: изменил данные — экран обновился сам.
     * (Ровно эту идею потом автоматизируют Vue-реактивность и React setState.)
     *
     * Почему стрелочная функция, а не просто this.#postView.render?
     * Если передать метод «голым»: store.on('change', this.#postView.render),
     * то внутри render ключевое слово `this` будет НЕ postView, а undefined
     * (в модулях действует строгий режим). Метод «отрывается» от объекта.
     * Стрелочная функция не имеет своего this и берёт его из окружения —
     * то есть из App, где this.#postView существует. Подробнее — ниже, у onLike.
     */
    this.#store.on('change', (posts) => this.#postView.render(posts));

    /* ---------- 2. Форма → Модель ----------
     * PostFormView сообщает: «отправили форму, вот { title, body }».
     * Мы просим Store создать пост.
     *
     * Конструктор Post бросает ошибку (throw), если заголовок или текст пустые.
     * Ловим её здесь через try/catch — это задача контроллера: решить,
     * КАК показать ошибку пользователю (alert, красная рамка, тост...).
     * Модель лишь говорит «так нельзя», а не «покажи окошко».
     */
    this.#formView.onSubmit(({ title, body }) => {
      try {
        this.#store.add(title, body);
        this.#formView.reset(); // очищаем форму только при успехе
      } catch (error) {
        alert(error.message);
      }
    });

    /* ---------- 3. Лайк: Представление → Модель ----------
     * Здесь для учебных целей показан ВТОРОЙ способ сохранить `this` — bind.
     *
     * this.#handleLike — это ссылка на функцию-метод. Сама по себе функция
     * не помнит, у какого объекта её взяли. Когда PostView позже вызовет
     * handler(id), это будет обычный вызов функции, и this внутри будет undefined.
     *
     * .bind(this) создаёт НОВУЮ функцию, у которой this навсегда «приклеен» к App.
     *
     * Два способа на практике:
     *   (а) стрелка:  view.onLike((id) => this.#handleLike(id))
     *   (б) bind:     view.onLike(this.#handleLike.bind(this))
     * Результат одинаковый. Стрелки сейчас встречаются чаще,
     * а bind вы увидите в старом коде, особенно в классовых компонентах React:
     *   this.handleClick = this.handleClick.bind(this);
     */
    this.#postView.onLike(this.#handleLike.bind(this));

    /* ---------- 4. Удаление: Представление → Модель ----------
     * Снова стрелка. confirm() показывает модальное окно и ВОЗВРАЩАЕТ true/false
     * (пока окно открыто, выполнение JS на странице приостановлено).
     * Можно было бы записать короче: confirm('...') && this.#store.remove(id)
     * — оператор && не вычислит правую часть, если левая false.
     * Но if читается понятнее, поэтому оставляем его.
     */
    this.#postView.onDelete((id) => {
      if (confirm('Удалить этот пост?')) {
        this.#store.remove(id);
      }
    });
  }

  /*
   * Обработчик лайка вынесен в отдельный приватный метод,
   * чтобы показать работу bind (см. выше).
   * В реальном проекте так делают, когда логика обработчика длиннее одной строки.
   */
  #handleLike(id) {
    // Если бы bind не было, здесь упали бы с ошибкой:
    // "Cannot read private member #store from an object whose class did not declare it"
    this.#store.like(id);
  }

  /*
   * start() — первый запуск.
   * Подписка на 'change' сработает только при ПЕРВОМ изменении данных,
   * а показать пустой список (с заглушкой «постов нет») нужно сразу.
   * Поэтому делаем начальную отрисовку вручную.
   *
   * Почему не в конструкторе? Принцип «конструктор только настраивает,
   * но не запускает побочных эффектов». Так объект можно создать заранее,
   * а запустить — когда удобно (например, после загрузки данных с сервера).
   * В React похожее разделение: рендер компонента и useEffect для эффектов.
   */
  start() {
    this.#postView.render(this.#store.getAll());
  }
}

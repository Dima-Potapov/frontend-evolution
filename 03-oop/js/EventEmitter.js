/**
 * ============================================================
 *  EventEmitter.js — базовый класс «издатель событий»
 * ============================================================
 *
 * ЗАЧЕМ ЭТОТ КЛАСС?
 * В v1 и v2 была одна большая проблема: после КАЖДОГО изменения данных
 * мы должны были ВРУЧНУЮ вызвать перерисовку (renderPosts / updateEmptyMessage).
 * Забыл вызвать — экран показывает устаревшие данные.
 *
 * Решение — паттерн «Наблюдатель» (Observer / Pub-Sub):
 *   — хранилище данных «издаёт» событие 'change', когда данные поменялись;
 *   — отображение «подписывается» на это событие и само перерисовывается.
 * Хранилищу не нужно знать, КТО его слушает. Слабая связанность!
 *
 * 💡 СВЯЗЬ С БУДУЩИМИ ВЕРСИЯМИ:
 * Именно эта идея («данные изменились → подписчики узнали → экран обновился»)
 * лежит в основе реактивности Vue (04), useState в React (05)
 * и хранилища Zustand (06). Здесь мы пишем её своими руками,
 * чтобы потом понимать, что делают фреймворки «под капотом».
 *
 * Кстати, браузер сам устроен так же: element.addEventListener('click', fn)
 * — это подписка на событие 'click' у «издателя» element.
 */

/**
 * export — делает класс доступным для других модулей.
 * Другой файл сможет написать: import { EventEmitter } from './EventEmitter.js';
 *
 * Без export класс был бы виден ТОЛЬКО внутри этого файла
 * (у каждого модуля своя область видимости).
 */
export class EventEmitter {
  /**
   * #listeners — ПРИВАТНОЕ поле класса (знак # в начале имени).
   *
   * Приватное = доступно ТОЛЬКО внутри методов этого класса.
   * Снаружи обращение emitter.#listeners вызовет СИНТАКСИЧЕСКУЮ ОШИБКУ.
   * Это настоящая защита на уровне языка (появилась в ES2022).
   *
   * Раньше программисты писали this._listeners — подчёркивание означало
   * «пожалуйста, не трогай», но защиты не было: трогать было можно.
   *
   * Map — коллекция «ключ → значение», похожа на объект {},
   * но ключом может быть что угодно и есть удобные методы get/set/has.
   * Здесь ключ — имя события ('change'), значение — массив функций-подписчиков.
   *
   * Поле объявлено прямо в теле класса (class field): оно создаётся
   * для КАЖДОГО нового объекта автоматически, до выполнения constructor.
   */
  #listeners = new Map();

  /**
   * on — подписаться на событие.
   *
   * @param {string} eventName — имя события, например 'change'
   * @param {Function} callback — функция, которую вызовут при событии
   * @returns {Function} — функция ОТПИСКИ. Вызови её — и подписка снимется.
   *
   * Возвращать функцию отписки — популярный приём.
   * Ровно так работает useEffect в React (05): эффект возвращает функцию очистки.
   */
  on(eventName, callback) {
    // Если для этого события ещё нет массива подписчиков — создаём пустой.
    if (!this.#listeners.has(eventName)) {
      this.#listeners.set(eventName, []);
    }

    // Добавляем подписчика в массив.
    // this — это КОНКРЕТНЫЙ объект, у которого вызвали метод
    // (например, store в выражении store.on(...)).
    this.#listeners.get(eventName).push(callback);

    // Возвращаем стрелочную функцию отписки.
    // Стрелочная функция «запоминает» this и callback из окружения (замыкание),
    // поэтому позже, когда её вызовут, она знает, кого и откуда удалять.
    return () => {
      const callbacks = this.#listeners.get(eventName);
      // filter создаёт НОВЫЙ массив без нашей функции.
      this.#listeners.set(
        eventName,
        callbacks.filter((cb) => cb !== callback)
      );
    };
  }

  /**
   * emit — «издать» событие: вызвать всех подписчиков.
   *
   * @param {string} eventName — имя события
   * @param  {...any} args — любые данные, которые получат подписчики
   *
   * ...args — rest-параметр: собирает ВСЕ переданные аргументы в массив.
   * emit('change', posts) → args = [posts]
   */
  emit(eventName, ...args) {
    // ?? [] — если подписчиков нет (undefined), берём пустой массив,
    // чтобы forEach не упал с ошибкой.
    const callbacks = this.#listeners.get(eventName) ?? [];

    // Вызываем каждого подписчика и передаём ему данные.
    // ...args здесь — spread: «раскладывает» массив обратно в аргументы.
    callbacks.forEach((callback) => callback(...args));
  }
}

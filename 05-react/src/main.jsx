/*
 * ============================================================
 *  main.jsx — ТОЧКА ВХОДА React-приложения
 * ============================================================
 *
 *  Сравните точки входа всех версий:
 *
 *   v1/v2: скрипт сам находит элементы и вешает обработчики.
 *   v3:    new App({ store, postView, formView }).start();
 *   v4:    createApp(App).mount('#app');
 *   v5:    createRoot(document.getElementById('root')).render(<App />);
 *
 *  Идея v4 и v5 одна: «возьми корневой компонент и отрисуй его в этот DOM-элемент».
 */

// StrictMode — специальный компонент-«проверяльщик» для режима разработки (см. ниже).
import { StrictMode } from 'react';

/*
 * React разделён на ДВА пакета:
 *  • react      — ядро: компоненты, хуки, Virtual DOM. Не знает ничего о браузере.
 *  • react-dom  — «рендерер» для браузера: превращает Virtual DOM в настоящий DOM.
 * Благодаря этому разделению существует React Native: то же ядро `react`,
 * но другой рендерер, который рисует нативные кнопки iOS/Android вместо <div>.
 * (Во Vue оба слоя лежат в одном пакете `vue`.)
 *
 * '/client' — потому что есть ещё react-dom/server для серверного рендеринга
 * (он понадобится в версии 07 с Next.js).
 */
import { createRoot } from 'react-dom/client';

import App from './App.jsx';

// Глобальные стили. Как и в v4, CSS импортируется из JS, а Vite вставляет его в <head>.
import './index.css';

/*
 * createRoot(элемент) — создаёт «корень» React внутри #root.
 * .render(<App />)    — отрисовывает в нём компонент App.
 *
 * <App /> — это JSX. Браузер такой синтаксис не понимает!
 * Плагин @vitejs/plugin-react перед отправкой в браузер превращает его в вызов функции:
 *     <App />   →   jsx(App, {})
 * Результат — обычный JS-объект-описание { type: App, props: {} },
 * то есть элемент Virtual DOM. Никакого HTML здесь нет.
 *
 * <StrictMode> в режиме разработки (npm run dev) специально:
 *  • вызывает функции компонентов ДВАЖДЫ, чтобы поймать «нечистые» компоненты,
 *    которые что-то меняют во время рендера;
 *  • монтирует, размонтирует и снова монтирует компоненты, чтобы проверить,
 *    что useEffect правильно «убирает за собой».
 * Поэтому, если добавить console.log в компонент, в консоли будет две строки — это НЕ баг.
 * В production-сборке (npm run build) StrictMode ничего не делает.
 */
createRoot(document.getElementById('root')).render(
  <StrictMode>
    <App />
  </StrictMode>
);

/**
 * ============================================================
 *  usePosts.js — ХРАНИЛИЩЕ постов в виде пользовательского ХУКА
 * ============================================================
 *
 *  Хук (hook, «крючок») — функция, имя которой начинается с use...,
 *  и которая «цепляется» за возможности React: состояние, эффекты, ссылки.
 *  Свой хук — это обычная функция, внутри которой вызываются встроенные хуки.
 *
 *  ── Родословная этого файла ──
 *   v3: class PostStore extends EventEmitter   — данные + события вручную
 *   v4: function usePostStore() { ref([]) }    — Vue composable, мутируем данные
 *   v5: function usePosts() { useReducer() }   — React-хук, данные НЕ мутируем
 *
 *  Внешне v4 и v5 очень похожи (оба называются use..., оба возвращают
 *  { posts, addPost, likePost, removePost }). Но внутри — главное идейное
 *  различие Vue и React:
 *
 *   VUE (v4): «Меняй данные как хочешь — я замечу». posts.value.unshift(...),
 *             post.likes++. Proxy перехватывает запись и знает, что перерисовать.
 *
 *   REACT (v5): «Я ничего не отслеживаю. Хочешь изменений — дай мне НОВОЕ
 *             состояние». React не использует Proxy. Он узнаёт об изменении,
 *             только когда вы вызываете setState / dispatch, и сравнивает
 *             старое и новое значение по ССЫЛКЕ (Object.is).
 *             Если вы сделаете posts.push(...) — массив тот же самый объект,
 *             ссылка не изменилась → React решит, что ничего не произошло,
 *             и экран НЕ обновится. Это самая частая ошибка новичков в React.
 *
 *  Поэтому в React данные ИММУТАБЕЛЬНЫ (неизменяемы): вместо изменения
 *  старого массива/объекта всегда создаём новый ([...arr], {...obj}, map, filter).
 */

import { useReducer, useRef, useCallback, useMemo } from 'react';

/* ============================================================
 *  REDUCER — «чистая функция переходов состояния»
 * ============================================================
 *
 *  reducer(текущееСостояние, действие) → новоеСостояние
 *
 *  Название от Array.prototype.reduce: состояние «сворачивается» из
 *  последовательности действий. Начали с [] → added → added → liked → removed → ...
 *
 *  Почему useReducer, а не просто useState?
 *   С useState логика изменений разбросана по функциям:
 *     setPosts(prev => [newPost, ...prev]); setPosts(prev => prev.map(...)); ...
 *   С useReducer ВСЕ правила изменения состояния собраны в одном месте,
 *   а компоненты лишь отправляют «действия» (actions) — что случилось.
 *   Это как App.js из v3 + PostStore в одной функции, только без побочных эффектов.
 *   Такой же подход лежит в основе Redux, а Zustand (v6) — его упрощение.
 *
 *  Правила reducer'а (нарушать нельзя):
 *   1. Чистота: тот же вход → тот же выход. Никаких Math.random(), Date.now(),
 *      запросов к серверу, confirm(), счётчиков id снаружи.
 *      ⚠️ StrictMode в режиме разработки вызывает reducer ДВАЖДЫ, чтобы поймать
 *      нечистый код. Если бы мы делали здесь nextId++, id прыгали бы через один!
 *   2. Иммутабельность: не менять state, а вернуть новый.
 *
 *  Функция объявлена ВНЕ хука: она не зависит ни от чего, кроме аргументов,
 *  и её можно протестировать отдельно, вообще без React:
 *    postsReducer([], { type: 'added', post: {...} }) → [{...}]
 */
function postsReducer(posts, action) {
  // switch по типу действия. Тип — просто строка, описывающая «что произошло»
  // (в прошедшем времени: added, а не add — это событие, а не команда).
  switch (action.type) {
    case 'added':
      // [новый, ...старые] — НОВЫЙ массив: сначала новый пост, затем
      // spread-оператор «раскладывает» все элементы старого массива.
      // [v4]: posts.value.unshift(post) — мутация старого массива. В React так нельзя.
      return [action.post, ...posts];

    case 'liked':
      // map создаёт НОВЫЙ массив. Изменённый пост — НОВЫЙ объект { ...post, likes: +1 }
      // (копируем все поля и перезаписываем likes). Остальные посты — те же
      // самые объекты (ссылки не изменились). Это важно для React.memo в PostCard:
      // React увидит, что у остальных карточек props не изменились, и не будет их перерисовывать.
      // [v4]: post.likes++ — мутация. В React экран бы не обновился.
      return posts.map((post) =>
        post.id === action.id ? { ...post, likes: post.likes + 1 } : post
      );

    case 'removed':
      // filter и так возвращает новый массив — здесь React, Vue (v4) и v3 совпадают.
      return posts.filter((post) => post.id !== action.id);

    default:
      // Неизвестное действие — скорее всего опечатка. Лучше громко упасть, чем молча игнорировать.
      throw new Error(`Неизвестное действие: ${action.type}`);
  }
}

export function usePosts() {
  /**
   * ── useReducer ──
   * const [состояние, dispatch] = useReducer(reducer, начальноеСостояние);
   *
   *  • posts    — текущий массив постов (обычный массив, без .value, как во Vue!).
   *  • dispatch — «отправить действие»: dispatch({ type: 'liked', id: 3 }).
   *
   * Что происходит под капотом при dispatch:
   *  1. React ставит действие в очередь (НЕ меняет posts мгновенно).
   *  2. Планирует повторный вызов функции компонента (ре-рендер).
   *  3. При ре-рендере вызывает postsReducer(старые posts, действие) → новые posts.
   *  4. Функция компонента выполняется ЗАНОВО целиком и возвращает новый JSX.
   *  5. React сравнивает новый Virtual DOM со старым (reconciliation)
   *     и вносит в настоящий DOM только разницу.
   *
   * Важно: в отличие от v3 (render всего списка) и как во v4 — точечные обновления DOM.
   * В отличие от v4 — React заново вызывает функцию компонента, а не следит за полями.
   *
   * Где хранится posts, если функция компонента вызывается заново каждый раз?
   * Не в локальной переменной (она бы обнулялась), а внутри React — в «ячейке»,
   * привязанной к этому компоненту. React находит ячейку по ПОРЯДКУ вызова хуков.
   * Отсюда главное правило хуков: вызывать их только на верхнем уровне,
   * никогда внутри if, циклов и вложенных функций — иначе порядок собьётся.
   */
  const [posts, dispatch] = useReducer(postsReducer, []);

  /**
   * ── useRef — «коробка», которая переживает ре-рендеры, но не вызывает их ──
   *
   * Счётчик id не отображается на экране, поэтому ре-рендер при его изменении не нужен.
   *  • Обычная переменная `let nextId = 1` внутри хука обнулялась бы при каждом рендере.
   *  • useState вызвал бы лишний ре-рендер при каждом изменении.
   *  • useRef даёт объект { current: 1 }: он один и тот же на всё время жизни компонента,
   *    а запись в .current React никак не отслеживает.
   *
   * [v4]: let nextId = 1 внутри composable — там функция вызывается ОДИН раз (setup),
   *       поэтому обычной переменной хватало. В React функция вызывается при КАЖДОМ рендере.
   * Это ключевое отличие моделей: setup во Vue выполняется один раз, тело React-компонента — много раз.
   */
  const nextIdRef = useRef(1);

  /**
   * ── useCallback — «запомнить функцию между рендерами» ──
   *
   * Каждый рендер создаёт ВСЕ функции внутри компонента заново.
   * Для JS две одинаковые по коду функции — РАЗНЫЕ объекты: (() => {}) !== (() => {}).
   * Если передать новую функцию в props карточке, обёрнутой в React.memo,
   * memo решит «props изменились» и перерисует её зря.
   *
   * useCallback(fn, [зависимости]) возвращает ТУ ЖЕ функцию, пока зависимости не изменились.
   * Зависимостей нет ([]): dispatch React гарантирует стабильным, а nextIdRef — тот же объект.
   *
   * Во Vue (v4) такой проблемы нет: setup выполняется один раз, функции создаются один раз.
   */
  const addPost = useCallback((title, body) => {
    const cleanTitle = title.trim();
    const cleanBody = body.trim();

    // Валидация и throw — как в v3 (конструктор Post) и v4 (addPost).
    if (!cleanTitle || !cleanBody) {
      throw new Error('Заполните заголовок и текст поста');
    }

    // id генерируем ЗДЕСЬ (в обработчике события, он вызывается один раз),
    // а не в reducer'е (он должен быть чистым и может вызываться дважды).
    const post = { id: nextIdRef.current++, title: cleanTitle, body: cleanBody, likes: 0 };
    dispatch({ type: 'added', post });
  }, []);

  const likePost = useCallback((id) => dispatch({ type: 'liked', id }), []);
  const removePost = useCallback((id) => dispatch({ type: 'removed', id }), []);

  /**
   * ── Производные значения ──
   *
   * posts.length — дешёвая операция, просто считаем при каждом рендере. Никакого хука не нужно.
   * В React вычисление «на лету» во время рендера — нормальный подход по умолчанию.
   *
   * useMemo(fn, [зависимости]) — аналог computed из v4: кеширует результат и
   * пересчитывает его, только если изменились зависимости (здесь — массив posts).
   * Разница с computed: во Vue зависимости находятся АВТОМАТИЧЕСКИ (Vue видит,
   * что вы читали), а в React их перечисляют РУКАМИ в массиве [posts].
   * Забыли зависимость — получите устаревшее значение (линтер eslint-plugin-react-hooks подскажет).
   *
   * Честно: для 10 постов useMemo не нужен, reduce выполнится за микросекунды.
   * Он здесь, чтобы показать связь с computed. Не оборачивайте всё подряд в useMemo.
   */
  const postsCount = posts.length;
  const totalLikes = useMemo(
    () => posts.reduce((sum, post) => sum + post.likes, 0),
    [posts]
  );

  // Публичный интерфейс — тот же, что у usePostStore в v4.
  return { posts, postsCount, totalLikes, addPost, likePost, removePost };
}

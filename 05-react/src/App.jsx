/*
 * ============================================================
 *  App.jsx — КОРНЕВОЙ компонент
 * ============================================================
 *
 *  Компонент в React — это просто ФУНКЦИЯ, которая возвращает JSX
 *  (описание того, что должно быть на экране).
 *
 *  Сравните «форму» компонента в разных версиях:
 *   v3:  class PostView { render(posts) { ...createElement... } }
 *   v4:  App.vue: <script setup> + <template> + <style scoped> — три блока, три языка
 *   v5:  function App() { ...логика...; return (<div>...</div>); } — всё на JavaScript
 *
 *  Главная мысль React: UI = f(state). Интерфейс — это функция от состояния.
 *  Изменилось состояние → React снова вызывает функцию → получает новое описание
 *  интерфейса → сравнивает со старым → обновляет в DOM только разницу.
 *  Мы никогда не пишем «найди кнопку и поменяй текст» (императивно, как v1–v3),
 *  мы описываем «при таком состоянии экран выглядит так» (декларативно, как v4).
 */

import { useEffect } from 'react';
import PostForm from './components/PostForm.jsx';
import PostList from './components/PostList.jsx';
import { usePosts } from './hooks/usePosts.js';

/*
 * CSS Modules: файл *.module.css импортируется как ОБЪЕКТ.
 * Vite переименовывает каждый класс в уникальный: .title → ._title_x7y2a_12
 * и кладёт соответствие в объект: styles.title === '_title_x7y2a_12'.
 * Итог тот же, что у <style scoped> в v4: стили одного компонента не задевают другие.
 * Способ разный: Vue добавляет атрибуты data-v-xxx, CSS Modules меняют имена классов.
 */
import styles from './App.module.css';

/*
 * export default function App() — имя компонента ОБЯЗАТЕЛЬНО с большой буквы.
 * По первой букве JSX отличает компоненты от HTML-тегов:
 *   <div />  → строка 'div'  → настоящий DOM-элемент;
 *   <App />  → переменная App → вызвать нашу функцию.
 */
export default function App() {
  /*
   * Тело функции выполняется при КАЖДОМ рендере (первом и всех последующих).
   * [v4]: <script setup> выполнялся ОДИН раз при создании компонента.
   * Это главное отличие ментальных моделей Vue и React — держите его в голове.
   *
   * Но usePosts() не создаёт новое хранилище каждый раз: хуки внутри
   * (useReducer, useRef) при повторных вызовах возвращают сохранённые значения.
   */
  const { posts, postsCount, totalLikes, addPost, likePost, removePost } = usePosts();

  /*
   * ── useEffect — побочные эффекты ──
   *
   * Рендер должен быть «чистым»: только посчитать JSX. А всё, что трогает
   * внешний мир (document.title, таймеры, запросы, localStorage, подписки),
   * выносится в useEffect. React выполнит его ПОСЛЕ того, как обновит DOM.
   *
   * Второй аргумент [postsCount] — массив зависимостей:
   *   • [postsCount] — запускать после рендера, если postsCount изменился;
   *   • []           — один раз после первого рендера;
   *   • без массива  — после КАЖДОГО рендера.
   *
   * Функция, которую возвращает эффект, — «уборка» (cleanup). React вызовет её
   * перед следующим запуском эффекта и при удалении компонента.
   * [v3]: точно так же store.on() возвращал функцию отписки.
   * [v4]: аналоги — watch / watchEffect и onMounted / onUnmounted.
   */
  useEffect(() => {
    document.title = postsCount > 0 ? `(${postsCount}) Лента постов` : 'Лента постов — React';
    return () => {
      // Здесь нечего отменять, но обычно тут clearInterval, removeEventListener, abort запроса.
    };
  }, [postsCount]);

  /*
   * return (...) — JSX. Круглые скобки нужны, чтобы вернуть многострочное выражение.
   *
   * Отличия JSX от HTML и от шаблонов Vue:
   *   • className вместо class (class — зарезервированное слово в JS);
   *   • {выражение} вместо {{ выражение }} — фигурные скобки означают
   *     «здесь обычный JavaScript». Значение экранируется автоматически (XSS не пройдёт);
   *   • нет директив v-if / v-for / v-model — вместо них обычный JS:
   *     &&, тернарный оператор ? :, массив.map(). Учить новый синтаксис почти не нужно.
   *   • onAddPost={addPost} вместо @add-post="addPost": в React нет emit,
   *     родитель просто передаёт ФУНКЦИЮ через props, а ребёнок её вызывает.
   *   • Должен быть ОДИН корневой элемент (или фрагмент <>...</>),
   *     потому что функция может вернуть только одно значение.
   */
  return (
    <div className={styles.app}>
      <h1 className={styles.title}>📝 Лента постов</h1>
      <p className={styles.subtitle}>Версия 5: React + Vite (хуки)</p>

      {/*
        Комментарий в JSX пишется только так — в фигурных скобках.

        onAddPost={addPost} — передаём функцию «вниз» как обычный prop.
        [v4]: <PostForm @add-post="addPost" /> и emit('add-post', ...) в ребёнке.
        [v3]: formView.onSubmit(handler) — та же идея «передать колбэк».
        Интересно, что React ближе к v3: «событие компонента» — это просто
        функция-колбэк в параметрах, без специального механизма emit.
      */}
      <PostForm onAddPost={addPost} />

      {/*
        Условный рендер через &&:
          условие && <JSX>  → если условие ложно, ничего не рисуется.
        [v4]: <p v-if="postsCount > 0">.

        ⚠️ Ловушка: {postsCount && <p>...</p>} при postsCount === 0 нарисует «0»
        (React рисует числа, а && возвращает левую часть). Поэтому пишем явное
        сравнение postsCount > 0, которое даёт true/false (их React не рисует).
      */}
      {postsCount > 0 && (
        <p className={styles.stats}>
          Постов: {postsCount} · Лайков всего: {totalLikes}
        </p>
      )}

      {/* Props вниз, колбэки вверх — то же правило, что и во Vue. */}
      <PostList posts={posts} onLike={likePost} onRemove={removePost} />
    </div>
  );
}

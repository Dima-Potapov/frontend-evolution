/*
 * ============================================================
 *  vite.config.js — настройки СБОРЩИКА Vite
 * ============================================================
 *
 *  [v1, v2, v3]: сборщика не было. Браузер сам читал index.html,
 *  style.css и .js-файлы ровно в том виде, в каком мы их написали.
 *
 *  [v4]: появляются .vue-файлы. Браузер НЕ умеет их читать: для него
 *  <template> внутри .js — это просто непонятный текст. Нужен инструмент,
 *  который «переведёт» .vue → обычный JavaScript + CSS. Этим занимается Vite
 *  (произносится «вит», от французского «быстрый»; автор — тот же Эван Ю,
 *  что создал Vue).
 *
 *  Что делает Vite:
 *   • npm run dev   — запускает dev-сервер. Файлы компилируются «на лету»
 *     при запросе браузера, а при сохранении файла страница обновляется
 *     мгновенно, без потери состояния (HMR — Hot Module Replacement).
 *   • npm run build — собирает оптимизированную версию в папку dist/
 *     (минифицированный JS/CSS, готовый для загрузки на хостинг).
 */

// defineConfig — просто функция-обёртка, которая ничего не меняет,
// но даёт редактору (VS Code) подсказки по всем опциям конфига.
import { defineConfig } from 'vite';

// Плагин, который учит Vite понимать .vue-файлы (Single File Components).
// Без него Vite выдал бы ошибку при import App from './App.vue'.
import vue from '@vitejs/plugin-vue';

export default defineConfig({
  // plugins — массив плагинов. Каждый плагин расширяет возможности Vite.
  // vue() компилирует <template> в render-функции, <script setup> — в обычный
  // JS-модуль, а <style scoped> — в CSS с уникальными data-атрибутами.
  plugins: [vue()],

  server: {
    // allowedHosts: true — разрешаем открывать dev-сервер по любому домену
    // (нужно, если сервер запущен в облаке и открывается по внешней ссылке).
    // Локально на вашем компьютере эта строка ни на что не влияет.
    allowedHosts: true,
  },
});

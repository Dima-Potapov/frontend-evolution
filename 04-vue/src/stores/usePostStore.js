/**
 * ============================================================
 *  usePostStore.js — ХРАНИЛИЩЕ постов в виде COMPOSABLE
 * ============================================================
 *
 * Composable («компонуемая функция») — это обычная JS-функция,
 * имя которой по соглашению начинается с use..., и которая внутри
 * использует реактивные возможности Vue (ref, computed, watch...).
 * Она «упаковывает» кусок состояния + логику, чтобы его можно было
 * переиспользовать в любом компоненте.
 *
 * ── Сравнение с PostStore из v3 ──
 *
 *  v3 (PostStore.js, ~120 строк)          v4 (этот файл)
 *  ─────────────────────────────          ──────────────────────────────
 *  class PostStore extends EventEmitter   function usePostStore()
 *  #posts = []                            const posts = ref([])
 *  getAll() { return [...this.#posts] }   не нужен: компонент читает posts
 *  add(title, body)                       addPost(title, body)
 *  like(id)                               likePost(id)
 *  remove(id)                             removePost(id)
 *  #notify() → emit('change', ...)        НЕ НУЖЕН! Vue сам узнаёт об изменениях
 *  EventEmitter.js (~100 строк)           НЕ НУЖЕН!
 *  store.on('change', render) в App.js    НЕ НУЖЕН!
 *
 * Главное отличие: в v3 после КАЖДОГО изменения мы обязаны были вызвать
 * #notify(), а App — подписаться и вызвать render(). Забыли — экран
 * не обновился. Во Vue данные РЕАКТИВНЫ: изменили posts — Vue сам
 * перерисует все места, где posts используется. Это и есть реактивность.
 *
 * 💡 Pinia (официальный стор Vue) и Zustand (React, версия 06) устроены
 * по той же идее: «состояние + функции-действия», просто с удобствами
 * (DevTools, общий экземпляр на всё приложение, плагины).
 */

// ref — создаёт реактивную «коробку» для значения.
// computed — создаёт вычисляемое (производное) значение с кешем.
import { ref, computed } from 'vue';

export function usePostStore() {
  /**
   * ── ref([]) — реактивный массив постов ──
   *
   * Почему нельзя просто написать `let posts = []`?
   * Обычная переменная — это просто ячейка памяти. Когда вы её меняете,
   * никто об этом не узнаёт: JavaScript не сообщает «переменная изменилась».
   * В v3 мы решали это вручную — через EventEmitter и emit('change').
   *
   * ref() кладёт значение в объект-обёртку { value: [] } и превращает его
   * в Proxy (специальный объект JS, который умеет перехватывать операции).
   *  • Когда компонент при отрисовке ЧИТАЕТ posts.value, Vue запоминает:
   *    «этот компонент зависит от posts» (это называется track — отслеживание).
   *  • Когда кто-то ЗАПИСЫВАЕТ posts.value = ... или меняет массив
   *    (unshift, likes++), Proxy это перехватывает и Vue говорит:
   *    «все, кто зависел от posts, — перерисуйтесь» (trigger — запуск).
   *
   * Зачем именно обёртка с .value? Потому что Proxy умеет следить только
   * за ОБЪЕКТАМИ. Примитив (число, строку) или саму переменную отследить
   * нельзя — поэтому значение кладут внутрь объекта и следят за его полем value.
   *
   * Реактивность ГЛУБОКАЯ: объекты внутри массива тоже становятся Proxy.
   * Поэтому post.likes++ (см. likePost) тоже вызовет перерисовку.
   */
  const posts = ref([]);

  /**
   * ── let nextId = 1 — обычная, НЕ реактивная переменная ──
   *
   * Счётчик id нигде не отображается на экране. Если бы мы сделали его ref,
   * Vue тратил бы силы на отслеживание, но перерисовывать из-за него нечего.
   * Правило: в ref кладём только то, от чего зависит ИНТЕРФЕЙС.
   * Всё служебное — обычными переменными.
   *
   * [v1/v2]: тот же приём — глобальная let nextId.
   * [v3]: статическое поле класса Post (static #nextId).
   * [v4]: переменная в ЗАМЫКАНИИ функции usePostStore — снаружи её не видно,
   *       как и приватное поле в v3, но без классов и решёток #.
   */
  let nextId = 1;

  /**
   * ── computed() — вычисляемые значения ──
   *
   * computed принимает функцию-«рецепт» и возвращает ref только для чтения.
   * Чем computed лучше обычной функции function totalLikes() { ... }?
   *  • Обычная функция пересчитывается при КАЖДОМ вызове (каждой перерисовке).
   *  • computed КЕШИРУЕТ результат: Vue помнит, что totalLikes зависит
   *    от posts и от likes каждого поста. Пока они не изменились,
   *    повторное чтение totalLikes.value мгновенно возвращает старый результат.
   *    Пересчёт происходит, только когда изменилась зависимость.
   *
   * Для массива из 3 постов разница незаметна, а для 10 000 — огромна.
   * Правило: всё, что можно ВЫЧИСЛИТЬ из состояния, не храните отдельно,
   * а описывайте через computed (иначе две копии данных рассинхронизируются).
   */
  const postsCount = computed(() => posts.value.length);

  // reduce — «сворачивает» массив в одно значение: начинаем с 0
  // и прибавляем likes каждого поста.
  const totalLikes = computed(() =>
    posts.value.reduce((sum, post) => sum + post.likes, 0)
  );

  /**
   * addPost — создать пост.
   *
   * Валидация как в v3 (конструктор Post): пустые строки недопустимы.
   * Бросаем ошибку (throw), а КАК её показать, решает компонент формы.
   * Стор не знает про интерфейс — тот же принцип разделения ответственности.
   */
  function addPost(title, body) {
    // trim() убирает пробелы по краям: «   » превратится в пустую строку.
    const cleanTitle = title.trim();
    const cleanBody = body.trim();

    if (!cleanTitle || !cleanBody) {
      throw new Error('Заполните заголовок и текст поста');
    }

    // Внутри JS-кода к содержимому ref обращаемся через .value!
    // posts — это обёртка, posts.value — сам массив.
    // unshift — добавить В НАЧАЛО (новые посты сверху), как в v3.
    //
    // Обратите внимание: после unshift мы НИЧЕГО не вызываем.
    // Ни render(), ни notify(), ни emit('change'). Vue сам заметит
    // изменение массива через Proxy и обновит экран.
    posts.value.unshift({
      id: nextId++, // сначала подставит текущее значение, потом увеличит счётчик
      title: cleanTitle,
      body: cleanBody,
      likes: 0,
    });
  }

  /**
   * likePost — +1 лайк.
   *
   * Мутируем объект напрямую: post.likes++.
   * [v3]: post.like() — метод модели, затем store.#notify().
   * [v4]: просто меняем поле. Объект post внутри posts.value — реактивный
   *       Proxy (глубокая реактивность ref), Vue перехватит запись в likes
   *       и перерисует ТОЛЬКО ту карточку, где изменилось число.
   *
   * ⚠️ В React (версия 05) так делать НЕЛЬЗЯ: там нужно создавать новый
   * объект ({ ...post, likes: post.likes + 1 }). Это одно из главных
   * идейных различий Vue (мутабельная реактивность) и React (иммутабельность).
   */
  function likePost(id) {
    const post = posts.value.find((p) => p.id === id);
    if (post) post.likes++;
  }

  /**
   * removePost — удалить пост.
   *
   * filter создаёт НОВЫЙ массив, и мы ЗАМЕНЯЕМ им старый: posts.value = ...
   * Запись в .value — тоже изменение, которое Vue отследит.
   * (Можно было бы и мутировать через splice — Vue это тоже поймёт.
   *  filter выбран ради сходства с v3 и будущим React.)
   *
   * confirm() здесь НЕТ: «спросить пользователя» — забота интерфейса,
   * а не хранилища. Он живёт в компоненте PostCard.vue.
   */
  function removePost(id) {
    posts.value = posts.value.filter((p) => p.id !== id);
  }

  /**
   * Возвращаем «публичный интерфейс» стора — то, что будет доступно
   * компонентам. Всё остальное (nextId) остаётся спрятанным в замыкании.
   *
   * ⚠️ Каждый вызов usePostStore() создаёт НОВЫЙ независимый набор данных
   * (как new PostStore() в v3). Поэтому мы вызываем его один раз — в App.vue —
   * и раздаём данные детям через props.
   * Если вынести `const posts = ref([])` ЗА пределы функции (на уровень модуля),
   * все вызовы получили бы ОДИН общий массив — так делают простой «глобальный стор».
   * Pinia решает этот вопрос «из коробки».
   */
  return { posts, postsCount, totalLikes, addPost, likePost, removePost };
}

<!--
  ============================================================
   PostList.vue — список карточек постов
  ============================================================

  Аналог метода render() класса PostView из v3 (и функции renderPosts из v1).

  [v3]: render(posts) стирал контейнер (replaceChildren()) и создавал
        ВСЕ карточки заново через #createCard, а потом переключал
        заглушку через classList.toggle('hidden', ...).
  [v4]: мы просто ОПИСЫВАЕМ, как список должен выглядеть при данном массиве.
        Когда массив меняется, Vue сам сравнивает старую и новую картину
        (Virtual DOM) и меняет в настоящем DOM только отличия.

  Это главный сдвиг мышления: от ИМПЕРАТИВНОГО стиля («создай элемент,
  вставь, удали, переключи класс») к ДЕКЛАРАТИВНОМУ («вот как должно быть»).
-->

<script setup>
import PostCard from './PostCard.vue';

/*
 * defineProps — объявляем ВХОДНЫЕ данные компонента (props).
 * Подробные объяснения — в PostCard.vue. Здесь короткая форма-объект:
 * имя пропса → настройки (тип и обязательность).
 */
defineProps({
  posts: { type: Array, required: true },
});

/*
 * Список сам ничего не делает с лайками и удалением: он лишь ПЕРЕДАЁТ
 * события карточек выше, в App.vue. Поэтому объявляет те же события.
 */
const emit = defineEmits(['like', 'remove']);
</script>

<template>
  <!--
    v-if / v-else — УСЛОВНАЯ ОТРИСОВКА.

    v-if="posts.length > 0" — если условие ложно, элемента НЕТ В DOM
    вообще (не скрыт, а именно отсутствует). Когда условие станет истинным,
    Vue создаст элемент; когда снова ложным — удалит.
    v-else — «иначе»: должен стоять сразу после элемента с v-if.

    Заметьте: в шаблоне пишем posts, а не props.posts — пропсы
    доступны в шаблоне напрямую.

    [v3]: this.#emptyMessage.classList.toggle('hidden', posts.length > 0) —
          заглушка всегда была в DOM, мы лишь прятали её через display:none.
          Это аналог v-show. Здесь использован v-if, потому что список и заглушка
          взаимоисключающие, и держать в DOM невидимый элемент незачем.
  -->
  <div v-if="posts.length > 0" class="posts-container">
    <!--
      v-for="post in posts" — ЦИКЛ в шаблоне: отрисовать <PostCard>
      для каждого элемента массива. Аналог posts.forEach(post => append(createCard(post))) из v3.

      :key="post.id" — УНИКАЛЬНЫЙ КЛЮЧ каждого элемента. Очень важная вещь!

      Зачем он нужен? При изменении массива Vue строит новый Virtual DOM
      и сравнивает со старым (этот процесс называют patching — «латание»).
      По ключу Vue понимает, КАКОЙ элемент какой:
        • добавили пост в начало → Vue видит новый key и создаёт ОДНУ карточку,
          остальные просто остаются на месте;
        • удалили пост с key=3 → Vue удаляет ровно эту карточку.

      Что будет без key (или с key="index")? Vue сопоставляет элементы
      по ПОЗИЦИИ: «первая карточка была про A, теперь про B — обновлю текст
      в первой, во второй, в третьей... и добавлю последнюю». При добавлении
      поста в начало переписываются ВСЕ карточки. А если внутри карточки было
      локальное состояние (введённый текст, фокус, анимация), оно «переедет»
      к чужому посту — классический баг.

      Правило: в key — стабильный уникальный id из данных, а не индекс массива.

      :post="post" — передаём объект поста в проп post карточки.

      @like="emit('like', $event)" — карточка сообщила «лайк» с id в payload.
        $event в обработчике события компонента — это первый аргумент emit,
        то есть id поста. Мы просто «пробрасываем» его выше.
      @remove="(id) => emit('remove', id)" — то же самое, записанное стрелкой
        (показаны оба варианта синтаксиса, они равнозначны).

      [v3]: делегирование событий — один addEventListener на контейнер,
            closest('.btn-like'), dataset.id, Number(...). Всё это больше
            НЕ НУЖНО: каждая карточка сама знает свой пост и сообщает его id.
    -->
    <PostCard
      v-for="post in posts"
      :key="post.id"
      :post="post"
      @like="emit('like', $event)"
      @remove="(id) => emit('remove', id)"
    />
  </div>

  <p v-else class="empty-message">
    Пока нет ни одного поста. Напишите первый! ✍️
  </p>
</template>


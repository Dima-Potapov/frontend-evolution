/*
 * ============================================================
 *  main.js — ТОЧКА ВХОДА приложения
 * ============================================================
 *
 *  Сравните с main.js из v3, где мы руками:
 *    1) искали DOM-элементы (document.getElementById...);
 *    2) создавали new PostStore(), new PostView(...), new PostFormView(...);
 *    3) связывали их через new App({ store, postView, formView });
 *    4) вызывали app.start() для первой отрисовки.
 *
 *  В Vue всё это сводится к ОДНОЙ строке: createApp(App).mount('#app').
 *  Искать элементы не нужно (компоненты сами описывают свою разметку),
 *  связывать вручную не нужно (это делает реактивность),
 *  вызывать первую отрисовку не нужно (mount сам рисует первый раз).
 */

// Именованный импорт функции createApp из пакета 'vue' (папка node_modules/vue).
// В v3 мы писали пути вида './PostStore.js'. Здесь путь — просто 'vue':
// это «голый» импорт (bare import). Браузер сам его не понимает,
// но Vite знает, что надо искать в node_modules, и подставит правильный файл.
import { createApp } from 'vue';

// Импорт CSS прямо в JavaScript! Для браузера это бессмыслица,
// но Vite понимает: «этот CSS нужно подключить на страницу».
// Здесь лежат только ГЛОБАЛЬНЫЕ стили (сброс, body, шрифт).
// Стили конкретных компонентов живут внутри их .vue-файлов (<style scoped>).
import './style.css';

// Импорт корневого компонента. App.vue — это не JS-файл, но благодаря
// плагину @vitejs/plugin-vue (см. vite.config.js) он превращается в
// обычный JS-объект «описание компонента», который мы и получаем здесь.
import App from './App.vue';

/*
 * createApp(App) — создать ЭКЗЕМПЛЯР приложения с корневым компонентом App.
 * .mount('#app') — «смонтировать»: отрисовать App и вставить результат
 *                  внутрь элемента <div id="app"> из index.html.
 *
 * ── Три способа запустить Vue, которые вы встретите в интернете ──
 *
 *  1) Vue 2, Options API (старый код, до 2020 года):
 *       new Vue({
 *         el: '#app',
 *         data: { posts: [] },              // состояние
 *         methods: { addPost() { ... } },   // функции
 *       });
 *     Одно глобальное приложение на страницу, создаётся через `new`.
 *
 *  2) Vue 3 через CDN (без сборщика, как jQuery в v2):
 *       <script src="https://unpkg.com/vue@3/dist/vue.global.js"></script>
 *       <script>
 *         Vue.createApp({ data() { return { posts: [] } } }).mount('#app');
 *       </script>
 *     Быстро для экспериментов, но нет .vue-файлов: шаблоны приходится
 *     писать строками или прямо в HTML, а компилятор шаблонов едет
 *     в браузер пользователя (+ лишние килобайты, медленнее старт).
 *
 *  3) Vue 3 + Vite (наш вариант, современный стандарт):
 *       createApp(App).mount('#app');
 *     Шаблоны компилируются ЗАРАНЕЕ (на этапе сборки), в браузер уходит
 *     только готовый JS. Можно создать несколько независимых приложений
 *     на одной странице (createApp возвращает отдельный экземпляр,
 *     а не меняет глобальный Vue, как в Vue 2).
 *
 *  Между createApp и mount можно подключать плагины:
 *     createApp(App).use(router).use(pinia).mount('#app');
 *  Роутер и Pinia (официальный стор) мы пока не используем — сделали свой
 *  простой стор в stores/usePostStore.js.
 */
createApp(App).mount('#app');

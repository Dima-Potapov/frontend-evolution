<!--
  ============================================================
   App.vue — КОРНЕВОЙ компонент приложения
  ============================================================

  Это SFC — Single File Component («однофайловый компонент»).
  Один .vue-файл = один компонент, и в нём ТРИ блока:

   <script setup> — ЛОГИКА: данные, функции, импорты (JavaScript).
   <template>     — РАЗМЕТКА: HTML-подобный шаблон с директивами Vue.
   <style scoped> — ВНЕШНИЙ ВИД: CSS, который действует только на этот компонент.

  [v1–v3]: HTML лежал в index.html, CSS — в style.css, JS — в main.js / js/*.js.
           Чтобы понять, как устроена «форма», надо было открыть ТРИ файла
           и мысленно связать их через id и классы.
  [v4]:    всё про один кусок интерфейса — в одном файле. Разделение идёт
           не «по технологиям» (HTML / CSS / JS), а «по смыслу» (форма / карточка / список).

  Что происходит под капотом (делает плагин @vitejs/plugin-vue при сборке):
   • <template> компилируется в render-функцию — JS-код, который создаёт
     виртуальные DOM-узлы (Virtual DOM — лёгкие JS-объекты-описания элементов).
   • <script setup> превращается в функцию setup() компонента; всё, что объявлено
     на верхнем уровне (переменные, функции, импорты), автоматически доступно в шаблоне.
   • <style scoped> превращается в обычный CSS, где к каждому селектору добавлен
     уникальный атрибут (например .app-title[data-v-7a7a37b1]).

  Роль App.vue — та же, что у App.js (контроллера) в v3: «дирижёр».
  Он владеет данными (стором) и связывает форму и список. Но «проводов»
  (подписок store.on, render, bind) больше нет — их заменила реактивность.
-->

<script setup>
/*
 * <script setup> — «синтаксический сахар» Composition API.
 *
 * Без setup пришлось бы писать (так выглядел ранний Vue 3):
 *   export default {
 *     components: { PostForm, PostList },
 *     setup() {
 *       const { posts, addPost } = usePostStore();
 *       return { posts, addPost }; // явно вернуть всё, что нужно шаблону
 *     }
 *   }
 * С <script setup> этот код выполняется так же — один раз при создании
 * компонента, — но возвращать ничего не нужно, а импортированные
 * компоненты сразу можно использовать как теги.
 *
 * А в Options API (Vue 2) логика раскладывалась по «полочкам»:
 *   data() { return { posts: [] } }, methods: { addPost() {...} }, computed: {...}
 * Composition API позволяет группировать код по СМЫСЛУ и выносить
 * его в composables (как наш usePostStore).
 */

// Импорт дочерних компонентов. Имя переменной (PostForm) сразу становится
// тегом, который можно использовать в шаблоне: <PostForm />.
// Регистрировать компонент (components: {...}) не нужно — это делает <script setup>.
import PostForm from './components/PostForm.vue';
import PostList from './components/PostList.vue';
import { usePostStore } from './stores/usePostStore.js';

/*
 * Создаём хранилище ОДИН раз — здесь, в корневом компоненте.
 * Деструктуризация { posts, ... } — вытаскиваем нужные поля из возвращённого объекта.
 *
 * [v3]: const store = new PostStore(); const app = new App({ store, ... });
 * [v4]: одна строка. Никаких подписок, никакого app.start().
 *
 * ⚠️ Деструктурировать ref безопасно: posts остаётся той же «коробкой»,
 * и реактивность не теряется. (А вот деструктуризация reactive()-объекта
 * реактивность ломает — об этом подробнее в документации Vue.)
 */
const { posts, postsCount, totalLikes, addPost, likePost, removePost } = usePostStore();
</script>

<template>
  <!--
    <template> — шаблон компонента. Выглядит как HTML, но это НЕ HTML:
    Vue скомпилирует его в JavaScript-функцию отрисовки.

    Во Vue 3 у шаблона может быть несколько корневых элементов,
    но мы оборачиваем всё в .app — как в v1–v3, ради того же CSS.
  -->
  <div class="app">
    <h1 class="app-title">📝 Лента постов</h1>
    <p class="app-subtitle">Версия 4: Vue 3 + Vite (Composition API)</p>

    <!--
      Подключаем дочерний компонент как тег.

      @add-post="addPost" — подписка на СОБЫТИЕ компонента PostForm.
      Когда PostForm выполнит emit('add-post', title, body), Vue вызовет
      нашу функцию addPost(title, body) из стора.

      [v3]: formView.onSubmit(({ title, body }) => store.add(title, body))
            — подписку настраивали руками в App.js.
      [v4]: то же самое, но декларативно — прямо в разметке.
    -->
    <PostForm @add-post="addPost" />

    <!--
      Мини-статистика: демонстрация computed.

      {{ postsCount }} — «интерполяция» (усы): вставить значение как ТЕКСТ.
      Vue экранирует его автоматически, поэтому XSS невозможен
      (как textContent в v1/v3; escapeHtml из v2 больше не нужна).

      Обратите внимание: в шаблоне пишем postsCount, а НЕ postsCount.value!
      Vue автоматически «разворачивает» ref'ы верхнего уровня в шаблоне:
      объект, через который шаблон обращается к данным, — это Proxy, который
      при чтении ref'а сам возвращает его .value. В <script> такой магии нет,
      там .value пишем явно.

      v-if — показываем строку, только когда есть хотя бы один пост.
      (Подробно про v-if и v-show — в PostList.vue и PostForm.vue.)
    -->
    <p v-if="postsCount > 0" class="stats">
      Постов: {{ postsCount }} · Лайков всего: {{ totalLikes }}
    </p>

    <!--
      Передача данных ВНИЗ (props) и подписка на события ВВЕРХ (emits).

      :posts="posts" — двоеточие = сокращение v-bind:posts.
        Значит: «значение атрибута — это JavaScript-выражение, а не строка».
        posts="posts" (без двоеточия) передал бы строку "posts"!
        Здесь ref разворачивается автоматически — ребёнок получит сам массив.

      @like / @remove — когда список сообщит «лайкнули пост id»,
        вызываем функции стора.

      Это главное правило компонентов: «props вниз, события вверх».
      Данные хранит и меняет только владелец (App), дети лишь показывают
      и сообщают о действиях пользователя. Ровно как в v3, где View
      только сообщала о кликах, а меняли данные App + Store.
    -->
    <PostList :posts="posts" @like="likePost" @remove="removePost" />
  </div>
</template>


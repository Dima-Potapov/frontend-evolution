// Этот файл содержит ВСЮ логику нашего приложения "Лента постов".
// Здесь мы работаем с:
//   — Массивом данных (хранилище постов)
//   — DOM (Document Object Model) — создаём и удаляем HTML-элементы через JS
//   — Событиями (events) — реагируем на действия пользователя
//
// Важно понимать: браузер читает этот файл СВЕРХУ ВНИЗ, строка за строкой.
// Поэтому порядок имеет значение: сначала объявляем функции, потом используем.
//
// Этот файл подключён в конце <body>, значит к моменту его выполнения
// все HTML-элементы уже существуют, и мы можем их находить через document.


// ===== 1. ХРАНИЛИЩЕ ДАННЫХ =====

/**
 * Массив для хранения всех постов.
 *
 * В реальном приложении данные хранятся на сервере (в базе данных).
 * Здесь мы храним их в оперативной памяти (в переменной).
 * Это значит: при перезагрузке страницы все посты ПРОПАДУТ.
 * В следующих версиях мы это исправим (localStorage, потом сервер).
 *
 * let, а не const — потому что мы будем менять содержимое массива
 * (добавлять, фильтровать). Хотя push/splice не меняют саму ссылку,
 * filter СОЗДАЁТ новый массив и присваивает его обратно.
 *
 * Каждый пост — это объект с полями:
 *   { id: число, title: строка, body: строка, likes: число }
 */
let posts = [];


/**
 * Счётчик для генерации уникальных ID.
 *
 * Каждому посту нужен уникальный идентификатор, чтобы мы могли:
 *   — Найти конкретный пост в массиве (для лайка или удаления)
 *   — Привязать HTML-элемент к данным (через data-атрибут)
 *
 * В реальном приложении ID генерирует база данных (автоинкремент).
 * Здесь мы делаем это вручную: каждый новый пост получает nextId,
 * после чего nextId увеличивается на 1.
 */
let nextId = 1;


// ===== 2. ПОЛУЧЕНИЕ ССЫЛОК НА DOM-ЭЛЕМЕНТЫ =====

/**
 * document.getElementById('id') — находит на странице элемент
 * с указанным id и возвращает ссылку на него.
 *
 * Это один из самых базовых методов работы с DOM.
 * DOM (Document Object Model) — это "дерево" из всех HTML-элементов.
 * JavaScript может читать это дерево, добавлять/удалять элементы,
 * менять их содержимое и стили.
 *
 * Мы сохраняем ссылки в константы (const), потому что
 * сами элементы не меняются — меняется их СОДЕРЖИМОЕ.
 */

// Форма для создания поста
const postForm = document.getElementById('post-form');

// Поле ввода заголовка
const titleInput = document.getElementById('post-title');

// Поле ввода текста поста
const bodyInput = document.getElementById('post-body');

// Контейнер, куда будем добавлять карточки постов
const postsContainer = document.getElementById('posts-container');

// Сообщение "Пока нет постов"
const emptyMessage = document.getElementById('empty-message');


// ===== 3. ФУНКЦИИ =====

/**
 * Функция createPostElement — создаёт HTML-карточку для одного поста.
 *
 * Принимает объект поста: { id, title, body, likes }
 * Возвращает DOM-элемент (HTMLDivElement), готовый для вставки на страницу.
 *
 * Почему мы создаём элементы через JS, а не пишем HTML?
 * Потому что посты ДИНАМИЧЕСКИЕ — их количество и содержимое зависят
 * от действий пользователя. Мы не можем заранее написать HTML
 * для постов, которых ещё не существует.
 *
 * @param {object} post — объект поста из массива posts
 * @returns {HTMLDivElement} — готовый DOM-элемент карточки
 */
function createPostElement(post) {
  // --- Создаём контейнер карточки ---

  /**
   * document.createElement('div') — создаёт новый HTML-элемент <div>.
   * Элемент пока "висит в воздухе" — он не прикреплён к странице.
   * Чтобы он появился, нужно добавить его в DOM (appendChild, prepend и т.д.).
   */
  const card = document.createElement('div');

  /**
   * className — свойство, задающее CSS-классы элементу.
   * Эквивалент атрибута class="post-card" в HTML.
   *
   * Почему className, а не class?
   * Потому что "class" — зарезервированное слово в JavaScript
   * (используется для объявления классов). Поэтому в DOM API
   * используется альтернативное имя: className.
   */
  card.className = 'post-card';

  /**
   * dataset — специальное свойство для работы с data-атрибутами.
   * card.dataset.id = post.id  →  создаёт атрибут data-id="значение" в HTML.
   *
   * Data-атрибуты — это способ хранить произвольные данные прямо в HTML-элементе.
   * Мы сохраняем ID поста, чтобы потом при клике на "Лайк" или "Удалить"
   * понять, КАКОЙ именно пост имеется в виду.
   *
   * Соглашение: data-атрибуты начинаются с data-, а в JS доступны через dataset.
   * data-id="5" → element.dataset.id === "5" (всегда строка!).
   */
  card.dataset.id = post.id;


  // --- Создаём заголовок ---

  const title = document.createElement('h2');

  /**
   * textContent — задаёт ТЕКСТОВОЕ содержимое элемента.
   *
   * ВАЖНО: textContent безопасен от XSS-атак!
   * XSS (Cross-Site Scripting) — вредоносный код, внедрённый через пользовательский ввод.
   * Если пользователь введёт "<script>alert('хак')</script>" в заголовок:
   *   — textContent: отобразит это КАК ТЕКСТ (безопасно)
   *   — innerHTML: ВЫПОЛНИТ скрипт (опасно!)
   *
   * Правило: для пользовательского ввода ВСЕГДА используй textContent.
   * innerHTML допустим только для контролируемого HTML (шаблоны, которые ты сам пишешь).
   */
  title.textContent = post.title;


  // --- Создаём текст поста ---

  const body = document.createElement('p');
  body.textContent = post.body;


  // --- Создаём панель с кнопками ---

  const actions = document.createElement('div');
  actions.className = 'post-actions';


  // --- Кнопка "Лайк" ---

  const likeBtn = document.createElement('button');

  /**
   * Задаём сразу несколько CSS-классов через пробел.
   * 'btn btn-like' — элемент получит стили от ОБОИХ классов.
   *
   * Если пост уже лайкнут (likes > 0), добавляем класс 'liked'
   * для визуального отличия (розовый фон).
   *
   * Тернарный оператор: условие ? значение_если_да : значение_если_нет
   * post.likes > 0 ? ' liked' : '' → если лайки есть, добавить ' liked', иначе пустая строка.
   */
  likeBtn.className = 'btn btn-like' + (post.likes > 0 ? ' liked' : '');

  /**
   * Текст кнопки: эмодзи сердца + количество лайков.
   * Шаблонная строка (template literal) с обратными кавычками `...`
   * позволяет вставлять переменные через ${...}.
   * Это удобнее, чем конкатенация: '❤️ ' + post.likes
   */
  likeBtn.textContent = `❤️ ${post.likes}`;

  /**
   * addEventListener — добавляет обработчик события.
   *
   * 'click' — тип события (клик мышью).
   * Второй аргумент — функция, которая вызовется при клике.
   *
   * Мы передаём СТРЕЛОЧНУЮ ФУНКЦИЮ (() => ...),
   * которая вызывает нашу функцию handleLike с ID этого поста.
   *
   * Почему не likeBtn.onclick = handleLike(post.id)?
   * Потому что handleLike(post.id) ВЫЗОВЕТ функцию прямо сейчас
   * и присвоит её РЕЗУЛЬТАТ (undefined) в onclick.
   * Нам нужна ССЫЛКА на функцию, которая вызовется ПОТОМ, при клике.
   * Стрелочная функция () => handleLike(post.id) — это именно обёртка,
   * которая "запоминает" post.id и вызовет handleLike только при клике.
   *
   * Это называется "замыкание" (closure) — одна из ключевых концепций JS.
   */
  likeBtn.addEventListener('click', () => handleLike(post.id));


  // --- Кнопка "Удалить" ---

  const deleteBtn = document.createElement('button');
  deleteBtn.className = 'btn btn-delete';
  deleteBtn.textContent = '🗑️ Удалить';
  deleteBtn.addEventListener('click', () => handleDelete(post.id));


  // --- Собираем карточку ---

  /**
   * appendChild — добавляет дочерний элемент В КОНЕЦ родителя.
   *
   * Порядок вызовов определяет порядок элементов на странице:
   * 1. В actions добавляем кнопку лайка, затем кнопку удаления
   * 2. В card добавляем заголовок, текст, панель кнопок
   *
   * Результат в DOM:
   * <div class="post-card">
   *   <h2>Заголовок</h2>
   *   <p>Текст</p>
   *   <div class="post-actions">
   *     <button>❤️ 0</button>
   *     <button>🗑️ Удалить</button>
   *   </div>
   * </div>
   */
  actions.appendChild(likeBtn);
  actions.appendChild(deleteBtn);

  card.appendChild(title);
  card.appendChild(body);
  card.appendChild(actions);

  // Возвращаем готовый элемент (пока НЕ на странице — вызывающий код решит, куда его поставить)
  return card;
}


/**
 * Функция updateEmptyMessage — показывает или прячет сообщение "Нет постов".
 *
 * Вызывается после каждого добавления/удаления поста.
 *
 * posts.length — количество элементов в массиве.
 * Если 0 — постов нет, показываем сообщение.
 * Если > 0 — посты есть, прячем сообщение.
 *
 * classList.add('hidden') — добавляет CSS-класс 'hidden' (display: none).
 * classList.remove('hidden') — убирает CSS-класс 'hidden'.
 *
 * classList — более современная альтернатива прямому изменению className.
 * С classList можно добавлять/убирать/переключать отдельные классы,
 * не затрагивая остальные. С className пришлось бы вручную разбирать строку.
 */
function updateEmptyMessage() {
  if (posts.length === 0) {
    emptyMessage.classList.remove('hidden');
  } else {
    emptyMessage.classList.add('hidden');
  }
}


/**
 * Функция handleAddPost — обрабатывает отправку формы (создание нового поста).
 *
 * @param {Event} event — объект события.
 * Браузер автоматически передаёт его в обработчик.
 * Содержит информацию о событии: тип, целевой элемент, координаты и т.д.
 */
function handleAddPost(event) {
  /**
   * event.preventDefault() — ОТМЕНЯЕТ стандартное поведение браузера.
   *
   * Для формы стандартное поведение — перезагрузить страницу
   * и отправить данные на сервер (GET/POST запрос).
   * Нам это не нужно! Мы обрабатываем данные ПРЯМО ЗДЕСЬ, в JavaScript.
   *
   * Без preventDefault() страница перезагрузится, и все данные потеряются,
   * потому что наш массив posts живёт только в оперативной памяти.
   */
  event.preventDefault();

  // --- Получаем значения из полей ---

  /**
   * .value — свойство input/textarea, содержащее введённый текст.
   * .trim() — убирает пробелы в начале и конце строки.
   *
   * Зачем trim()? Чтобы пользователь не создал "пустой" пост
   * из одних пробелов: "   " → "" → пустая строка → не пройдёт проверку.
   */
  const title = titleInput.value.trim();
  const body = bodyInput.value.trim();

  // --- Валидация ---

  /**
   * Проверяем, что оба поля заполнены.
   * !title — если строка пустая (""), она "falsy" в JavaScript.
   * !"" === true, !"Hello" === false.
   *
   * || — логическое ИЛИ: если ХОТЯ БЫ одно поле пустое, выходим.
   * return — выходим из функции, пост не создаётся.
   *
   * Хотя у нас есть HTML-атрибут required, он не сработает,
   * если пользователь введёт только пробелы. Это дополнительная защита.
   */
  if (!title || !body) {
    return;
  }

  // --- Создаём объект поста ---

  /**
   * Объект (Object) — набор пар "ключ: значение".
   * Это основная структура данных для представления сущностей в JS.
   *
   * id: nextId++ — присваиваем текущее значение nextId,
   * а ПОТОМ увеличиваем его на 1 (постфиксный инкремент).
   * Первый пост получит id=1, второй id=2, и т.д.
   *
   * title: title — сокращённая запись ES6.
   * Если имя ключа совпадает с именем переменной, можно писать просто title
   * вместо title: title. Мы пишем полную форму для ясности.
   */
  const newPost = {
    id: nextId++,
    title: title,
    body: body,
    likes: 0,
  };

  // --- Добавляем пост в массив ---

  /**
   * push() — добавляет элемент В КОНЕЦ массива.
   * Другие методы: unshift() — в начало, splice() — в произвольную позицию.
   */
  posts.push(newPost);

  // --- Добавляем карточку поста на страницу ---

  /**
   * prepend() — добавляет элемент В НАЧАЛО контейнера.
   * Новый пост появляется СВЕРХУ ленты (как в соцсетях).
   *
   * Альтернатива: appendChild() — добавляет в конец.
   * Мы используем prepend, чтобы новые посты были наверху.
   */
  const postElement = createPostElement(newPost);
  postsContainer.prepend(postElement);

  // --- Очищаем форму ---

  /**
   * form.reset() — встроенный метод формы: сбрасывает все поля к начальным значениям.
   * Удобнее, чем вручную очищать каждое поле:
   *   titleInput.value = '';
   *   bodyInput.value = '';
   */
  postForm.reset();

  /**
   * focus() — ставит курсор в указанное поле.
   * UX-деталь: после публикации пользователь сразу может писать следующий пост,
   * не кликая мышкой. Маленькие вещи делают интерфейс приятнее.
   */
  titleInput.focus();

  // Обновляем видимость сообщения "Нет постов"
  updateEmptyMessage();
}


/**
 * Функция handleLike — увеличивает счётчик лайков поста.
 *
 * @param {number} postId — ID поста, который нужно лайкнуть.
 */
function handleLike(postId) {
  /**
   * find() — метод массива, возвращает ПЕРВЫЙ элемент,
   * для которого переданная функция вернёт true.
   *
   * post => post.id === postId — стрелочная функция (arrow function).
   * Для каждого элемента массива проверяет: его id === искомому postId?
   *
   * === (строгое равенство) — сравнивает и значение, И тип.
   * 5 === 5 → true, 5 === "5" → false.
   * Всегда используй === вместо == (нестрогое: 5 == "5" → true — сюрприз!).
   *
   * Если пост не найден, find вернёт undefined.
   */
  const post = posts.find(post => post.id === postId);

  // Защита: если пост не найден (уже удалён?), ничего не делаем
  if (!post) {
    return;
  }

  // Увеличиваем счётчик лайков
  post.likes += 1;

  // --- Обновляем карточку в DOM ---

  /**
   * querySelector — мощный метод поиска элементов по CSS-селектору.
   *
   * `[data-id="${postId}"]` — атрибутный селектор:
   * найти элемент с атрибутом data-id, равным нашему postId.
   *
   * Обратные кавычки `...` позволяют вставить переменную через ${}.
   * Если postId = 3, получится строка: [data-id="3"]
   *
   * Мы ищем в postsContainer (а не во всём document),
   * чтобы сузить область поиска — это чуть эффективнее.
   */
  const cardElement = postsContainer.querySelector(`[data-id="${postId}"]`);

  if (cardElement) {
    /**
     * Находим кнопку лайка внутри ЭТОЙ карточки.
     * .querySelector('.btn-like') — ищет элемент с классом btn-like
     * только внутри cardElement, а не по всей странице.
     */
    const likeBtn = cardElement.querySelector('.btn-like');

    if (likeBtn) {
      // Обновляем текст кнопки новым количеством лайков
      likeBtn.textContent = `❤️ ${post.likes}`;

      /**
       * classList.add('liked') — добавляем класс для визуального изменения.
       * Если класс уже есть — ничего не произойдёт (не добавится дубликат).
       */
      likeBtn.classList.add('liked');
    }
  }
}


/**
 * Функция handleDelete — удаляет пост.
 *
 * @param {number} postId — ID поста для удаления.
 */
function handleDelete(postId) {
  /**
   * confirm() — встроенная функция браузера.
   * Показывает модальное окно с текстом и кнопками "OK" / "Отмена".
   * Возвращает true (OK) или false (Отмена).
   *
   * Это простой способ запросить подтверждение опасного действия.
   * В реальном приложении вместо confirm используют красивые модальные окна.
   */
  const confirmed = confirm('Удалить этот пост?');

  // Если пользователь нажал "Отмена" — выходим
  if (!confirmed) {
    return;
  }

  // --- Удаляем пост из массива ---

  /**
   * filter() — метод массива, возвращает НОВЫЙ массив,
   * содержащий только элементы, для которых функция вернула true.
   *
   * post => post.id !== postId — "оставить все посты, ID которых НЕ равен удаляемому".
   * !== — строгое неравенство.
   *
   * ВАЖНО: filter НЕ изменяет исходный массив! Он создаёт НОВЫЙ.
   * Поэтому мы присваиваем результат обратно в posts.
   * Старый массив уходит в "сборку мусора" (garbage collection).
   *
   * Альтернатива: splice(index, 1) — мутирует массив напрямую.
   * filter чище и понятнее, хотя чуть менее эффективен (создаёт копию).
   * На небольших массивах разница не ощущается.
   */
  posts = posts.filter(post => post.id !== postId);

  // --- Удаляем карточку из DOM ---

  const cardElement = postsContainer.querySelector(`[data-id="${postId}"]`);

  if (cardElement) {
    /**
     * remove() — удаляет элемент из DOM.
     * Элемент полностью исчезает со страницы.
     *
     * Старый способ (до ES6): cardElement.parentNode.removeChild(cardElement);
     * remove() — гораздо проще!
     */
    cardElement.remove();
  }

  // Обновляем видимость сообщения "Нет постов"
  updateEmptyMessage();
}


// ===== 4. ПРИВЯЗКА СОБЫТИЙ =====

/**
 * Подписываемся на событие 'submit' формы.
 *
 * 'submit' срабатывает когда:
 *   — Пользователь нажимает кнопку type="submit"
 *   — Пользователь нажимает Enter в любом поле формы
 *
 * handleAddPost — ссылка на функцию (без скобок!).
 * Если написать handleAddPost() — функция ВЫЗОВЕТСЯ сразу,
 * а в addEventListener передастся её результат (undefined).
 *
 * Это ключевое отличие:
 *   handleAddPost   → ссылка на функцию ("вот функция, вызови её потом")
 *   handleAddPost() → вызов функции ("вызови прямо сейчас и верни результат")
 */
postForm.addEventListener('submit', handleAddPost);


// ===== 5. ИНИЦИАЛИЗАЦИЯ =====

